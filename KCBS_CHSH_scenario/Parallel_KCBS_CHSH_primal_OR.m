%% SDP variables

X = sdpvar(n+1, n+1, 'symmetric');


%% Constraints

% First constraints
Constraints = [X(1,1) == 1, X >= 0];     

% Diagonal constraints:
for i = 2:n+1
    Constraints = [Constraints, X(i,i) == X(1,i)];  
end

% Exclusivity constraints
for k = 1:size(pairs,1)
    i = 1+pairs(k,1);
    j = 1+pairs(k,2);                            
    Constraints = [Constraints, X(i,j) == 0];
end


%% Objective function

Objective = 0;
for i = 2:n+1
    Objective = Objective + X(i,i);
end



%% Optimization using MOSEK

opts = sdpsettings('solver','mosek','verbose',1);
Sol=optimize(Constraints, -Objective, opts);



