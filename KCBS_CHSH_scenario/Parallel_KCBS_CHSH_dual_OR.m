%% SDP VARIABLES

lamda = sdpvar(n,1);
mu    = sdpvar(n,1);
t     = sdpvar(1,1);

muEX = cell(n,1);

for k = 1:36
    muEX{k} = sdpvar(length(EX{k}),1);
end


%% Construction of dual matrix Z


Z1 = t*(E(:,1)*E(:,1)');



Z2 = 0;

for i = 1:n
    Z2 = Z2 + (lamda(i)-1)*E(:,i+1)*E(:,i+1)';
end


Z3 = 0;

for i = 1:n
    Z3 = Z3 + lamda(i) * ...
        (E(:,1)*E(:,i+1)' + E(:,i+1)*E(:,1)')/2;
end



Z4 = 0;

for i = 1:(n-1)

    Z4 = Z4 + mu(i) * ...
        (E(:,i+1)*E(:,i+2)' + E(:,i+2)*E(:,i+1)')/2;

end

Z4 = Z4 + mu(n) * ...
    (E(:,n+1)*E(:,2)' + E(:,2)*E(:,n+1)')/2;



C = 0;

for v = 1:36

    mu_v = muEX{v};

    for k = 1:length(EX{v})

        w = EX{v}(k);

        C = C + mu_v(k) * ...
            (E(:,v+1)*E(:,w+1)' + ...
             E(:,w+1)*E(:,v+1)')/2;

    end
end



Z = Z1 + Z2 - Z3 + Z4 + C;


%% SDP


Constraints = [Z >= 0, t >= 0];

Objective = t;

opts = sdpsettings( ...
    'solver','mosek', ...
    'verbose',1);

Sol = optimize(Constraints,Objective,opts);

%% Results

if Sol.problem ~= 0
    error(Sol.info);
end

